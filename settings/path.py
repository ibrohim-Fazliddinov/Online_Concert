"""
Module: path_settings.py

Модуль содержит класс `PathSettings` для управления путями к файлам окружения.
"""

import logging
import os
from pathlib import Path

logger = logging.getLogger(__name__)


class PathSettings:
    """
    Конфигурация путей для загрузки переменных окружения.

    Атрибуты:
        ENV_FILE (Path):
            Относительный путь до файла .env по умолчанию,
            если переменная окружения ENV_FILE не задана.
        env_path (str):
            Путь к файлу окружения, считанный из переменной окружения ENV_FILE.
            Если ENV_FILE не установлена, используется значение ENV_FILE по умолчанию.
    """

    # Относительный путь к файлу .env по умолчанию (один уровень выше текущей папки)
    ENV_FILE: Path = Path("../.env")

    # Пытаемся взять путь к файлу окружения из переменной ОС;
    # если её нет, используем путь по умолчанию
    env_path: str = os.getenv("ENV_FILE", str(ENV_FILE))

    # Логируем, какой файл окружения будет использоваться
    logger.info("Используем файл окружения: %s", env_path)

